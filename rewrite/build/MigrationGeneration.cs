using System;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.Build.Framework;

namespace MelodyTrack.Rewrite.Build
{
    public sealed class InvalidMigrationSource : Exception
    {
        public InvalidMigrationSource(string message) : base(message) { }
    }

    public sealed class MigrationSource
    {
        public long Version { get; set; }
        public string Name { get; set; } = "";
        public string Checksum { get; set; } = "";
        public string Sql { get; set; } = "";
        public string Handler { get; set; } = "";
    }

    public static class MigrationGeneration
    {
        public static MigrationSource[] Load(string directory)
        {
            if (!System.IO.Directory.Exists(directory))
                throw new InvalidMigrationSource("Не найден каталог миграций.");

            var sources = System.IO.Directory.GetFiles(directory)
                .Where(path => Path.GetExtension(path) == ".sql" || Path.GetExtension(path) == ".cs")
                .Select(Read).OrderBy(source => source.Version).ToArray();
            for (var index = 1; index < sources.Length; index++)
                if (sources[index - 1].Version == sources[index].Version)
                    throw new InvalidMigrationSource("Одинаковый номер миграций: " + sources[index - 1].Name + " и " + sources[index].Name + ".");
            return sources;
        }

        private static MigrationSource Read(string path)
        {
            var name = Path.GetFileName(path);
            var match = Regex.Match(name, @"\A(?<version>[0-9]{4})_(?<handler>[A-Z][A-Za-z0-9]*)\.(?<kind>sql|cs)\z");
            if (!match.Success || long.Parse(match.Groups["version"].Value) == 0)
                throw new InvalidMigrationSource("Неверное имя миграции " + name + ".");
            var bytes = File.ReadAllBytes(path);
            string content;
            try { content = new UTF8Encoding(false, true).GetString(bytes).TrimStart('\uFEFF'); }
            catch (DecoderFallbackException) { throw new InvalidMigrationSource("Миграция " + name + " должна быть в кодировке UTF-8."); }
            if (string.IsNullOrWhiteSpace(content))
                throw new InvalidMigrationSource("Миграция " + name + " пуста.");
            using (var hash = SHA256.Create())
            {
                return new MigrationSource
                {
                    Version = long.Parse(match.Groups["version"].Value), Name = name,
                    Checksum = BitConverter.ToString(hash.ComputeHash(bytes)).Replace("-", ""),
                    Sql = match.Groups["kind"].Value == "sql" ? content : "",
                    Handler = match.Groups["kind"].Value == "cs" ? match.Groups["handler"].Value : ""
                };
            }
        }

        public static string Render(string namespaceName, MigrationSource[] migrations)
        {
            if (!Regex.IsMatch(namespaceName, @"\A[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*\z"))
                throw new InvalidMigrationSource("Неверное пространство имён миграций.");
            var code = new StringBuilder("// <auto-generated/>\nnamespace " + namespaceName + ";\n\ninternal static class GeneratedMigrations\n{\n    internal static readonly global::MelodyTrack.Rewrite.Init.Migration[] All =\n    [\n");
            foreach (var migration in migrations)
            {
                var handler = migration.Handler.Length == 0
                    ? "context => global::MelodyTrack.Rewrite.Init.SqlMigration.RunAsync(" + Literal(migration.Sql) + ", context)"
                    : "global::" + namespaceName + ".Migrations." + migration.Handler + ".RunAsync";
                code.Append("        new(").Append(migration.Version).Append("L, ").Append(Literal(migration.Name))
                    .Append(", ").Append(Literal(migration.Checksum)).Append(", ").Append(handler).Append("),\n");
            }
            return code.Append("    ];\n}\n").ToString();
        }

        private static string Literal(string value)
        {
            var result = new StringBuilder("\"");
            foreach (var character in value)
            {
                if (character == '\\' || character == '"') result.Append('\\').Append(character);
                else if (character < 32 || character > 126) result.Append("\\u").Append(((int)character).ToString("X4"));
                else result.Append(character);
            }
            return result.Append('"').ToString();
        }

        public static void Generate(string directory, string output, string namespaceName)
        {
            var content = Render(namespaceName, Load(directory));
            System.IO.Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(output))!);
            if (!File.Exists(output) || File.ReadAllText(output) != content)
                File.WriteAllText(output, content, new UTF8Encoding(false));
        }
    }

    public sealed class GenerateMigrationRegistry : Microsoft.Build.Utilities.Task
    {
        [Required] public string Directory { get; set; } = "";
        [Required] public string Output { get; set; } = "";
        [Required] public string Namespace { get; set; } = "";

        public override bool Execute()
        {
            try { MigrationGeneration.Generate(Directory, Output, Namespace); return true; }
            catch (InvalidMigrationSource error) { Log.LogError(error.Message); return false; }
            catch (Exception error) { Log.LogError("Migration generation failed ({0}).", error.GetType().Name); return false; }
        }
    }
}

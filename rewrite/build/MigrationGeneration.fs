module MelodyTrack.Rewrite.Build.MigrationGeneration

open System
open System.IO
open System.Security.Cryptography
open System.Text
open System.Text.Json
open System.Text.RegularExpressions

type SourceBody = Sql of string | FSharp of string

type Source =
    { Version: int64
      Name: string
      Checksum: string
      Body: SourceBody }

exception InvalidMigrationSource of string

let private read (path: string) =
    let name = Path.GetFileName(path) |> nonNull
    let matched = Regex.Match(name, @"\A(?<version>[0-9]{4})_(?<module>[A-Z][A-Za-z0-9]*)\.(?<kind>sql|fs)\z")

    if not matched.Success then
        raise (InvalidMigrationSource $"Неверное имя миграции {name}.")

    let version = Int64.Parse(matched.Groups["version"].Value)

    if version = 0L then
        raise (InvalidMigrationSource $"Номер миграции {name} должен быть больше нуля.")

    let bytes = File.ReadAllBytes(path)

    let content =
        try UTF8Encoding(false, true).GetString(bytes).TrimStart('\uFEFF')
        with :? DecoderFallbackException ->
            raise (InvalidMigrationSource $"Миграция {name} должна быть в кодировке UTF-8.")

    if String.IsNullOrWhiteSpace(content) then
        raise (InvalidMigrationSource $"Миграция {name} пуста.")

    { Version = version
      Name = name
      Checksum = Convert.ToHexString(SHA256.HashData(bytes))
      Body =
        if matched.Groups["kind"].Value = "sql" then Sql content
        else FSharp matched.Groups["module"].Value }

let load (directory: string) =
    if not (Directory.Exists(directory)) then
        raise (InvalidMigrationSource "Не найден каталог миграций.")

    let migrations =
        Directory.GetFiles(directory, "*", SearchOption.TopDirectoryOnly)
        |> Array.filter (fun path ->
            let extension = Path.GetExtension(path)
            extension = ".sql" || extension = ".fs")
        |> Array.map read
        |> Array.sortBy (fun migration -> migration.Version)

    match migrations |> Array.pairwise |> Array.tryFind (fun (left, right) -> left.Version = right.Version) with
    | Some(left, right) ->
        raise (InvalidMigrationSource $"Одинаковый номер миграций: {left.Name} и {right.Name}.")
    | None -> migrations

let render (namespaceName: string) (migrations: Source array) =
    let literal (value: string) = JsonSerializer.Serialize(value)
    let entries =
        migrations
        |> Array.map (fun migration ->
            let handler =
                match migration.Body with
                | Sql sql -> "SqlMigration.run " + literal sql
                | FSharp name -> $"{namespaceName}.Migrations.{name}.run"

            $"        {{ Version = {migration.Version}L; Name = {literal migration.Name}; Checksum = {literal migration.Checksum}; Run = {handler} }}")

    String.concat "\n"
        [ $"// <auto-generated/>\nmodule {namespaceName}.GeneratedMigrations"
          "open MelodyTrack.Rewrite.Init"
          "let all: Migration array ="
          "    [|"
          String.concat "\n" entries
          "    |]\n" ]

let generate directory output namespaceName =
    let migrations = load directory
    let content = render namespaceName migrations
    let outputDirectory = Path.GetDirectoryName(Path.GetFullPath(output)) |> nonNull
    Directory.CreateDirectory(outputDirectory) |> ignore

    let writeIfChanged path value =
        if not (File.Exists(path)) || File.ReadAllText(path) <> value then
            File.WriteAllText(path, value, UTF8Encoding(false))

    let sources =
        migrations
        |> Array.choose (fun migration ->
            match migration.Body with
            | Sql _ -> None
            | FSharp _ ->
                Path.Combine(directory, migration.Name)
                |> Path.GetFullPath
                |> fun path -> Some(Path.GetRelativePath(Environment.CurrentDirectory, path)))
        |> String.concat "\n"

    writeIfChanged output content
    writeIfChanged (output + ".sources") sources

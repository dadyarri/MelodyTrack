import { describe, expect, it } from "vitest";
import { normalizeOptionals } from "./normalize-kiota-optionals";

describe("Kiota optional properties", () => {
  it("allows undefined only for optional property types and remains idempotent", () => {
    const source = `// Generated by Microsoft Kiota
interface Model {
  value?: string | null;
  required: string;
  existing?: number | undefined;
  method?(arg?: string): void;
}`;

    const result = normalizeOptionals(source);

    expect(result).toContain("value?: string | null | undefined;");
    expect(result).toContain("required: string;");
    expect(result).toContain("existing?: number | undefined;");
    expect(result).toContain("method?(arg?: string): void;");
    expect(normalizeOptionals(result)).toBe(result);
  });

  it("refuses to transform application source", () => {
    expect(() => normalizeOptionals("interface Model { value?: string; }")).toThrow(
      "Expected Kiota output",
    );
  });

  it("stops when the generator changes the expected property syntax", () => {
    expect(() =>
      normalizeOptionals("// Generated by Microsoft Kiota\n  value?: () => void;"),
    ).toThrow("Unexpected Kiota optional property type");
  });
});

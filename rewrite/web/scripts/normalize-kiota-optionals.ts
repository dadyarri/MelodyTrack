import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

// Kiota assigns undefined from ParseNode getters to optional properties.
// Express that in their types without relaxing exactOptionalPropertyTypes.
export function normalizeOptionals(source: string): string {
  if (!source.includes("// Generated by Microsoft Kiota")) throw new Error("Expected Kiota output");
  return source.replace(
    /^(\s*[a-zA-Z_$][\w$]*\?: )([^;\r\n]+);$/gm,
    (_line, property: string, type: string) => {
      // Fail rather than guess if Kiota changes its one-line property syntax.
      if (/[{}()]/.test(type)) throw new Error("Unexpected Kiota optional property type");
      return `${property}${/\bundefined\b/.test(type) ? type : `${type} | undefined`};`;
    },
  );
}

function normalizeDirectory(directory: string) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) normalizeDirectory(path);
    else if (entry.name.endsWith(".ts")) {
      const source = readFileSync(path, "utf8");
      const normalized = normalizeOptionals(source);
      if (source !== normalized) writeFileSync(path, normalized);
    }
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  normalizeDirectory(fileURLToPath(new URL("../src/shared/api/generated/", import.meta.url)));
}
